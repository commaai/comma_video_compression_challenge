#!/usr/bin/env python3
"""Generate tcm1_tables.h: constant integer tables for tcm.c (floating point only here, offline).

log2_tab[m], m in 0..4096 : round(65536 * log2(1 + m/4096))         (Q16 log2 mantissa, used by stretch)
squash_tab[j], j in 0..8190: clamp(round(2^32 / (1 + exp(-(j-4095)/256))), 1, 2^32-1)   (P(bit=1), 32-bit)
rate_tab[n], n in 0..4095 : round(65536 / (n + 1.5))                   (adaptive counter step, Q16)
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent / "tcm1_tables.h"
log2t = [round(65536 * math.log2(1 + m / 4096)) for m in range(4097)]
sq = [min(2**32 - 1, max(1, round(2**32 / (1 + math.exp(-(j - 4095) / 256))))) for j in range(8191)]
rate = [round(65536 / (n + 1.5)) for n in range(4096)]


def arr(name, ctype, vals):
    return f"static const {ctype} {name}[{len(vals)}] = {{{','.join(str(v) + ('u' if ctype == 'uint32_t' else '') for v in vals)}}};\n"


OUT.write_text("/* generated by gen_tables1.py - do not edit */\n#pragma once\n#include <stdint.h>\n"
               + arr("log2_tab", "uint32_t", log2t) + arr("squash_tab", "uint32_t", sq) + arr("rate_tab", "uint16_t", rate))
print("wrote", OUT)
