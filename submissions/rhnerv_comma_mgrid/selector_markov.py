def install_tables_from_payload(codes: np.ndarray) -> None:
    """Recompute module tables from 600 FEC6 mode indices (build time only)."""
    global SELECTOR_MARG, SELECTOR_TRANS
    trans = np.full((16, 16), 0.1, dtype=np.float64)
    for i in range(1, len(codes)):
        trans[int(codes[i - 1]), int(codes[i])] += 1.0
    trans = trans / trans.sum(axis=1, keepdims=True)
    marg = np.full(16, 0.6, dtype=np.float64)
    for a in range(16):
        marg[a] += int((codes == a).sum())
    marg = marg / marg.sum()
    SELECTOR_MARG = marg
    SELECTOR_TRANS = trans
